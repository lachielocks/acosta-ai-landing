function Refs({ src }: { src?: SourceKey[] }) {
  if (!src?.length) return null;
  return (
    <sup className="ml-0.5 whitespace-nowrap">
      {src.map((k, i) => (
        <Fragment key={k}>
          {i > 0 && <span className="text-muted-foreground">,</span>}
          <a
            href={sources[k].href}
            target="_blank"
            rel="noopener noreferrer"
            title={sources[k].label}
            aria-label={`Source ${num(k)}: ${sources[k].label}`}
            className="font-mono text-[10px] text-muted-foreground underline-offset-2 hover:text-primary hover:underline"
          >
            {num(k)}
          </a>
        </Fragment>
      ))}
    </sup>
  );
}

